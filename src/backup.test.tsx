import { nativeReplies, withIncome } from './test-native';
import { render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { expect, test, vi } from 'vitest';
import { invoke } from '@tauri-apps/api/core';
import App from './App';

vi.mock('@tauri-apps/api/core', () => ({ invoke: vi.fn() }));

test('导出要求重复输入合格密码，取消文件选择不导出，成功后清空密码', async () => {
  const user = userEvent.setup();
  vi.mocked(invoke).mockReset().mockImplementation(nativeReplies([{value:{ accounts: [], entries: [] }},{value:null},{value:'C:/backups/portfolio.grahambak'},{value:undefined}]));
  render(<App />);
  await user.click(await screen.findByRole('button', { name: '备份与恢复' }));
  const password = screen.getByLabelText('设置备份密码');
  const repeat = screen.getByLabelText('再次输入密码');
  const submit = screen.getByRole('button', { name: '选择位置并导出' });
  expect(submit).toBeDisabled();
  await user.type(password, '验收用备份口令-2026-only');
  await user.type(repeat, '不一致');
  expect(submit).toBeDisabled();
  await user.clear(repeat);
  await user.type(repeat, '验收用备份口令-2026-only');
  await user.click(submit);
  expect(await screen.findByText('已取消导出')).toBeVisible();
  expect(invoke).not.toHaveBeenCalledWith('export_backup', expect.anything());
  await user.click(submit);
  expect(await screen.findByText(/加密备份已保存/)).toHaveTextContent('portfolio.grahambak');
  expect(password).toHaveValue('');
  expect(repeat).toHaveValue('');
  expect(invoke).toHaveBeenCalledWith('export_backup', { path: 'C:/backups/portfolio.grahambak', password: '验收用备份口令-2026-only' });
});

test('恢复先验证摘要并确认，成功后清空密码和旧撤回状态并展示恢复前备份位置', async () => {
  const user = userEvent.setup();
  const account = { id: 'a', name: '旧账户', currency: 'CNY', balance: '10.00', archived: false, hasHistory: true };
  const entry = { id: 'e', accountId: 'a', amount: '10.00', occurredOn: '2026-10-25', note: '', source: '手动录入', deleted: false, revisionId: 1 };
  const preview = { createdAt: '2026-10-25T10:00:00Z', accountCount: 1, recordCount: 1, deletedCount: 0, fingerprint: 'verified-ciphertext' };
  const restored = { accounts: [{ ...account, id: 'b', name: '备份账户', balance: '7.70' }], entries: [{ ...entry, id: 'restored', accountId: 'b', amount: '7.70' }] };
  vi.mocked(invoke).mockReset().mockImplementation(nativeReplies([{value:{ accounts: [account], entries: [entry] }},{value:{ accounts: [{ ...account, balance: '0.00' }], entries: [{ ...entry, deleted: true, revisionId: 2 }] }},{value:'C:/backups/portfolio.grahambak'},{value:preview},{value:{ snapshot: restored, recoveryPath: 'C:/local/backups/before.grahambak' }}]));
  render(<App />);
  await user.click(await screen.findByRole('button', { name: '删除记录' }));
  await user.click(screen.getByRole('button', { name: '确认删除' }));
  expect(await screen.findByRole('button', { name: '撤回' })).toBeVisible();
  await user.click(screen.getByRole('button', { name: '备份与恢复' }));
  await user.click(screen.getByRole('button', { name: '选择备份文件' }));
  await user.type(screen.getByLabelText('恢复密码'), '验收用备份口令-2026-only');
  await user.click(screen.getByRole('button', { name: '验证备份' }));
  expect(await screen.findByText('1 个账户 · 1 条记录 · 其中 0 条已删除')).toBeVisible();
  const restore = screen.getByRole('button', { name: '确认恢复' });
  expect(restore).toBeDisabled();
  expect(invoke).not.toHaveBeenCalledWith('restore_backup', expect.anything());
  await user.click(screen.getByRole('checkbox', { name: '我确认用此备份替换当前账本' }));
  await user.click(restore);
  expect(await screen.findByText(/账本已恢复/)).toHaveTextContent('before.grahambak');
  expect(screen.getByLabelText('恢复密码')).toHaveValue('');
  expect(invoke).toHaveBeenCalledWith('restore_backup', { path: 'C:/backups/portfolio.grahambak', password: '验收用备份口令-2026-only', fingerprint: 'verified-ciphertext' });
  await user.click(screen.getByRole('button', { name: '账户与记录' }));
  expect(await screen.findByRole('cell', { name: '备份账户' })).toBeVisible();
  expect(screen.getByText('+¥7.70')).toBeVisible();
  expect(screen.queryByRole('button', { name: '撤回' })).not.toBeInTheDocument();
  expect(screen.queryByText('旧账户')).not.toBeInTheDocument();
});

test('密码变化使预览失效，验证或恢复失败时保留当前账本', async () => {
  const user = userEvent.setup();
  const account = { id: 'a', name: '保留账户', currency: 'USD', balance: '9.00', archived: false, hasHistory: false };
  const preview = { createdAt: '2026-10-25T10:00:00Z', accountCount: 0, recordCount: 0, deletedCount: 0, fingerprint: 'verified' };
  vi.mocked(invoke).mockReset().mockImplementation(nativeReplies([{value:{ accounts: [account], entries: [] }},{value:'C:/backups/portfolio.grahambak'},{value:'密码错误，当前账本未修改',reject:true},{value:preview},{value:preview},{value:'备份文件已变化，请重新验证后再恢复',reject:true}]));
  render(<App />);
  await user.click(await screen.findByRole('button', { name: '备份与恢复' }));
  await user.click(screen.getByRole('button', { name: '选择备份文件' }));
  await user.type(screen.getByLabelText('恢复密码'), 'wrong');
  await user.click(screen.getByRole('button', { name: '验证备份' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('密码错误');
  expect(screen.queryByRole('button', { name: '确认恢复' })).not.toBeInTheDocument();
  await user.clear(screen.getByLabelText('恢复密码'));
  await user.type(screen.getByLabelText('恢复密码'), 'the right password');
  await user.click(screen.getByRole('button', { name: '验证备份' }));
  expect(await screen.findByRole('button', { name: '确认恢复' })).toBeDisabled();
  await user.type(screen.getByLabelText('恢复密码'), ' changed');
  expect(screen.queryByRole('button', { name: '确认恢复' })).not.toBeInTheDocument();
  await user.click(screen.getByRole('button', { name: '验证备份' }));
  await user.click(await screen.findByRole('checkbox', { name: '我确认用此备份替换当前账本' }));
  await user.click(screen.getByRole('button', { name: '确认恢复' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('备份文件已变化');
  expect(screen.queryByRole('button', { name: '确认恢复' })).not.toBeInTheDocument();
  await user.click(screen.getByRole('button', { name: '账户与记录' }));
  expect(screen.getAllByText('保留账户').length).toBeGreaterThan(0);
  expect(screen.getByText('$9.00')).toBeVisible();
});
